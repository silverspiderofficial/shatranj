/// Lightweight bilingual (Persian / English) string table.
///
/// Persian is the default language. Chess notation (FEN, PGN, UCI, SAN)
/// is never translated and never uses Persian digits.
class AppStrings {
  const AppStrings(this.isFa);

  final bool isFa;

  String t(String key) {
    final table = isFa ? _fa : _en;
    return table[key] ?? _en[key] ?? key;
  }

  /// Formats [key] replacing `{0}`, `{1}`, ... with [args].
  String f(String key, List<Object> args) {
    var s = t(key);
    for (var i = 0; i < args.length; i++) {
      s = s.replaceAll('{$i}', n(args[i].toString()));
    }
    return s;
  }

  /// Converts Latin digits to Persian digits when the UI language is Persian.
  String n(Object value) => isFa ? toPersianDigits(value.toString()) : value.toString();

  static String toPersianDigits(String input) {
    const latin = '0123456789';
    const persian = '۰۱۲۳۴۵۶۷۸۹';
    final b = StringBuffer();
    for (final ch in input.split('')) {
      final i = latin.indexOf(ch);
      b.write(i >= 0 ? persian[i] : ch);
    }
    return b.toString();
  }

